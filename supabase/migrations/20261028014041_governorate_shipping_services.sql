  alter column amount drop not null,
  add column service_type text not null default 'standard' check(service_type in ('standard','express')),
  add column delivery_min_hours integer default 48 check(delivery_min_hours>0),
  add column delivery_max_hours integer default 120 check(delivery_max_hours>0),
  add column business_days boolean not null default true,
  add constraint shipping_enabled_rate_required check(not enabled or amount is not null),
  add constraint shipping_window_order check(delivery_min_hours is null or delivery_max_hours is null or delivery_min_hours<=delivery_max_hours);

